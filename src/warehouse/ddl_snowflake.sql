-- ====================================================================
-- PropIQ - Snowflake Cloud Data Warehouse DDL Architecture
-- ====================================================================

-- 1. Virtual Warehouse & Database Setup
CREATE WAREHOUSE IF NOT EXISTS PROPIQ_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Virtual warehouse for PropIQ real estate analytics';

CREATE DATABASE IF NOT EXISTS PROPIQ_DW
    DATA_RETENTION_TIME_IN_DAYS = 7;

CREATE SCHEMA IF NOT EXISTS PROPIQ_DW.RAW_STAGING;
CREATE SCHEMA IF NOT EXISTS PROPIQ_DW.CORE_STAR_SCHEMA;

USE SCHEMA PROPIQ_DW.CORE_STAR_SCHEMA;

-- 2. Dimensions
CREATE OR REPLACE TABLE DIM_DATE (
    DATE_KEY INT PRIMARY KEY,
    FULL_DATE DATE NOT NULL,
    DAY_OF_MONTH INT,
    DAY_NAME VARCHAR(15),
    DAY_OF_WEEK INT,
    MONTH INT,
    MONTH_NAME VARCHAR(15),
    QUARTER INT,
    YEAR INT,
    YEAR_MONTH VARCHAR(7),
    IS_WEEKEND INT
);

CREATE OR REPLACE TABLE DIM_LOCATION (
    LOCATION_KEY VARCHAR(32) PRIMARY KEY,
    CITY VARCHAR(64) NOT NULL,
    LOCALITY VARCHAR(128) NOT NULL,
    TRANSIT_SCORE INT,
    SAFETY_SCORE INT,
    SCHOOL_SCORE INT,
    METRO_DISTANCE_KM NUMBER(5, 2),
    HOSPITAL_COUNT INT
);

CREATE OR REPLACE TABLE DIM_PROPERTY_TYPE (
    PROPERTY_TYPE_KEY VARCHAR(32) PRIMARY KEY,
    BHK_COUNT INT NOT NULL,
    BHK_LABEL VARCHAR(16),
    PROPERTY_CATEGORY VARCHAR(32),
    FURNISHING_STATUS VARCHAR(32)
);

CREATE OR REPLACE TABLE DIM_AMENITIES (
    AMENITY_KEY VARCHAR(32) PRIMARY KEY,
    HAS_PARKING INT,
    HAS_GYM INT,
    HAS_SWIMMING_POOL INT,
    HAS_CLUBHOUSE INT,
    HAS_SECURITY INT,
    HAS_POWER_BACKUP INT,
    AMENITY_TIER VARCHAR(16)
);

-- 3. Snowflake Clustered Fact Table (Automatic Micro-partitioning)
CREATE OR REPLACE TABLE FACT_PROPERTY_LISTINGS (
    LISTING_ID VARCHAR(64) NOT NULL,
    DATE_KEY INT NOT NULL REFERENCES DIM_DATE(DATE_KEY),
    LOCATION_KEY VARCHAR(32) NOT NULL REFERENCES DIM_LOCATION(LOCATION_KEY),
    PROPERTY_TYPE_KEY VARCHAR(32) NOT NULL REFERENCES DIM_PROPERTY_TYPE(PROPERTY_TYPE_KEY),
    AMENITY_KEY VARCHAR(32) NOT NULL REFERENCES DIM_AMENITIES(AMENITY_KEY),
    CITY VARCHAR(64) NOT NULL,
    YEAR_MONTH VARCHAR(7) NOT NULL,
    PRICE_INR NUMBER(12, 0) NOT NULL,
    RENT_INR NUMBER(8, 0) NOT NULL,
    CARPET_AREA_SQFT NUMBER(8, 2) NOT NULL,
    PRICE_PER_SQFT NUMBER(10, 2),
    RENTAL_YIELD_PCT NUMBER(5, 2),
    BATHROOMS INT,
    BALCONIES INT,
    DAYS_ON_MARKET INT,
    LATITUDE NUMBER(9, 6),
    LONGITUDE NUMBER(9, 6),
    SOURCE_PORTAL VARCHAR(32)
)
CLUSTER BY (CITY, YEAR_MONTH);

-- 4. Snowpipe for Continuous Automated S3 Ingestion
CREATE OR REPLACE STAGE PROPIQ_DW.RAW_STAGING.S3_RAW_LISTINGS_STAGE
    URL = 's3://propiq-data-lake/raw/listings/'
    FILE_FORMAT = (TYPE = 'PARQUET');

CREATE OR REPLACE PIPE PROPIQ_DW.RAW_STAGING.PIPE_LISTINGS_AUTO_INGEST
    AUTO_INGEST = TRUE
    AS
    COPY INTO PROPIQ_DW.CORE_STAR_SCHEMA.FACT_PROPERTY_LISTINGS
    FROM @PROPIQ_DW.RAW_STAGING.S3_RAW_LISTINGS_STAGE
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
